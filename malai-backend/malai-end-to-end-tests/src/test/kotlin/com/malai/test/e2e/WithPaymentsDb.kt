package com.malai.test.e2e

import com.malai.test.acceptance.kensa.CallableAction
import com.malai.test.acceptance.kensa.fixtures.DatabaseConnection
import java.util.UUID

/**
 * E2E direct-database helpers for the `payments` table. The harness has no in-process Spring
 * context, so payment-lifecycle assertions (e.g. PENDING -> SETTLED after the SQS round-trip)
 * happen by polling Postgres via JDBC. Mirrors [WithFunding]'s direct-DB shape.
 */
interface WithPaymentsDb {

    /**
     * Block until the payment with [paymentId] reaches [expectedState], or fail. Use after a
     * cross-bank payment to wait out the (payments-service -> SQS -> malai-stub -> SQS ->
     * payments-service) round-trip: malai-stub's StubFpsScheme poller fires every 500ms,
     * payments-service's FpsOutboundSettledPoller fires every 500ms, so the typical round-trip
     * resolves within ~1.5s. The 30s default timeout gives plenty of headroom for slower CI
     * runners.
     */
    fun thePaymentReachesStateInTheDatabase(
        paymentId: UUID,
        expectedState: String,
        timeoutMs: Long = 30_000L,
        pollIntervalMs: Long = 250L,
    ) = CallableAction {
        val deadline = System.currentTimeMillis() + timeoutMs
        var lastSeen: String? = null
        while (System.currentTimeMillis() < deadline) {
            lastSeen = readPaymentState(paymentId)
            if (lastSeen == expectedState) return@CallableAction
            Thread.sleep(pollIntervalMs)
        }
        error("Payment $paymentId did not reach state '$expectedState' within ${timeoutMs}ms (last seen: $lastSeen)")
    }

    /**
     * Assert the payment holds [expectedState] for [forMs] and never leaves it. The inverse of
     * [thePaymentReachesStateInTheDatabase]: use it where a state change would be the bug. The
     * default window outlasts one turn of the five-second ReferredPaymentResolver sweep, so a
     * payment that survives it has been seen by the resolver and deliberately left alone.
     */
    fun thePaymentStaysInStateInTheDatabase(
        paymentId: UUID,
        expectedState: String,
        forMs: Long = 6_000L,
        pollIntervalMs: Long = 250L,
    ) = CallableAction {
        val deadline = System.currentTimeMillis() + forMs
        while (System.currentTimeMillis() < deadline) {
            val seen = readPaymentState(paymentId)
            if (seen != expectedState) {
                error("Payment $paymentId left state '$expectedState' for '$seen' within ${forMs}ms")
            }
            Thread.sleep(pollIntervalMs)
        }
    }

    /**
     * Block until at least one payment with [direction] and [expectedState] exists for the
     * given beneficiary account. Use for inbound flows where the paymentId is generated by
     * payments-service when it consumes the inbound-notify message and the test JVM has no
     * way to predict it. Throws on timeout.
     */
    fun aPaymentForBeneficiaryReachesStateInTheDatabase(
        beneficiaryAccountId: UUID,
        direction: String,
        expectedState: String,
        timeoutMs: Long = 30_000L,
        pollIntervalMs: Long = 250L,
    ) = CallableAction {
        val deadline = System.currentTimeMillis() + timeoutMs
        while (System.currentTimeMillis() < deadline) {
            if (readSinglePaymentIdForBeneficiary(beneficiaryAccountId, direction, expectedState) != null) {
                return@CallableAction
            }
            Thread.sleep(pollIntervalMs)
        }
        error(
            "No payment with direction=$direction state=$expectedState for beneficiary " +
                "$beneficiaryAccountId appeared within ${timeoutMs}ms"
        )
    }

    private fun readPaymentState(paymentId: UUID): String? =
        DatabaseConnection.createConnection(MalaiE2ETestContext.DATABASE_URL).use { conn ->
            conn.prepareStatement("SELECT state FROM payments WHERE payment_id = ?").use { ps ->
                ps.setObject(1, paymentId)
                val rs = ps.executeQuery()
                if (rs.next()) rs.getString("state") else null
            }
        }

    private fun readSinglePaymentIdForBeneficiary(
        beneficiaryAccountId: UUID,
        direction: String,
        expectedState: String,
    ): UUID? =
        DatabaseConnection.createConnection(MalaiE2ETestContext.DATABASE_URL).use { conn ->
            conn.prepareStatement(
                """
                SELECT payment_id FROM payments
                WHERE beneficiary_account_id = ? AND direction = ? AND state = ?
                """.trimIndent()
            ).use { ps ->
                ps.setObject(1, beneficiaryAccountId)
                ps.setString(2, direction)
                ps.setString(3, expectedState)
                val rs = ps.executeQuery()
                if (rs.next()) UUID.fromString(rs.getString("payment_id")) else null
            }
        }
}

package com.malai.accounts.identifier

import com.malai.accounts.entity.AccountIdentifierEntity
import com.malai.accounts.entity.IdentifierType.IBAN_BIC
import com.malai.accounts.entity.IdentifierType.SORT_CODE
import com.malai.commons.config.UuidGenerator
import org.springframework.stereotype.Component
import java.util.*

/**
 * Builds the SORT_CODE + IBAN_BIC [AccountIdentifierEntity] pair that every newly-created
 * account must have. Called from both create-account paths
 * ([com.malai.accounts.service.AccountsService.createAccount] and
 * [com.malai.accounts.service.OnboardingAccountsService.createAccount]) so identifiers are
 * generated consistently regardless of how the account was created.
 *
 *  - The bank-level fields (sort code, BIC) come from [BankIdentifierProperties].
 *  - The 8-digit account number is generated by [AccountNumberGenerator], which in production
 *    pulls from the `account_number_seq` Postgres sequence. Sequences are monotonic and
 *    non-transactional, so each call returns a never-before-issued value — collisions are
 *    impossible by construction. Callers wrap the insert in a try/catch on
 *    `DataIntegrityViolationException` purely as defense in depth against the
 *    `(identifier_type, account_identifier)` unique constraint.
 *  - The IBAN is computed deterministically from sort code + account number via [IbanCalculator].
 */
@Component
class AccountIdentifierFactory(
    private val bankIdentifiers: BankIdentifierProperties,
    private val accountNumberGenerator: AccountNumberGenerator,
    private val uuidGenerator: UuidGenerator,
) {

    fun identifiersFor(accountId: UUID): List<AccountIdentifierEntity> {
        val accountNumber = accountNumberGenerator.generate()
        val iban = IbanCalculator.ukIban(
            bic = bankIdentifiers.bic,
            sortCode = bankIdentifiers.sortCode,
            accountNumber = accountNumber,
        )
        return listOf(
            AccountIdentifierEntity(
                identifierId = uuidGenerator.generate(),
                accountId = accountId,
                identifierType = SORT_CODE,
                bankIdentifier = bankIdentifiers.sortCode,
                accountIdentifier = accountNumber,
            ),
            AccountIdentifierEntity(
                identifierId = uuidGenerator.generate(),
                accountId = accountId,
                identifierType = IBAN_BIC,
                bankIdentifier = bankIdentifiers.bic,
                accountIdentifier = iban,
            ),
        )
    }
}
